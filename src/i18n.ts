const DICTS: Record<Lang, Dict> = { zh: ZH, en: EN };

/* ── Detect browser language ── */
function detectLang(): Lang {
  if (typeof navigator === 'undefined') return 'zh';
  const langs = navigator.languages || [navigator.language || ''];
  for (const l of langs) {
    if (l.startsWith('zh')) return 'zh';
    if (l.startsWith('en')) return 'en';
  }
  return 'zh';
}

let _currentLang: Lang = detectLang();
const _listeners: Set<() => void> = new Set();

export function getLang(): Lang { return _currentLang; }

export function setLang(l: Lang) {
  _currentLang = l;
  if (typeof localStorage !== 'undefined') localStorage.setItem('ses_lang', l);
  _listeners.forEach(fn => fn());
}

export function toggleLang() {
  setLang(_currentLang === 'zh' ? 'en' : 'zh');
}

export function onLangChange(fn: () => void): () => void {
  _listeners.add(fn);
  return () => _listeners.delete(fn);
}

if (typeof localStorage !== 'undefined') {
  const saved = localStorage.getItem('ses_lang') as Lang | null;
  if (saved === 'zh' || saved === 'en') _currentLang = saved;
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const dict = DICTS[_currentLang];
  let msg = dict[key] || ZH[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      msg = msg.replace(`{${k}}`, String(v));
    }
  }
  return msg;
}
